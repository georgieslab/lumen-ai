/**
 * Helper to get translations for given language code with fallback to en-US
 */
export function getTranslations(langCode = 'en-US') {
  return TRANSLATIONS[langCode] || TRANSLATIONS['en-US'];
}

/**
 * Format string template with replacement parameters
 * E.g. formatString("Tech Jobs: {role} in {location}", { role: 'Frontend', location: 'Vienna' })
 */
export function formatString(template, vars = {}) {
  if (!template) return '';
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    return vars[key] !== undefined ? vars[key] : match;
  });
}
